import mongoose, { Schema } from "mongoose";
const schema = new Schema({
  saleId: { type: Schema.Types.ObjectId, required: true },
  saleLineId: { type: Schema.Types.ObjectId, required: true, index: true },
  customerId: { type: Schema.Types.ObjectId, required: true },
  receiptNumber: String,
  productName: String,
  inventoryType: { type: String, enum: ["BODEGA", "GROCERY"], required: true },
  quantity: { type: Number, required: true, min: 0 },
  unit: String,
  baseQuantity: Number,
  creditAmount: Number,
  condition: { type: String, enum: ["RESTOCKABLE", "DAMAGED"], required: true },
  reason: { type: String, required: true },
  status: { type: String, enum: ["PENDING_REVIEW", "APPROVED_AWAITING_POSTING", "POSTED", "REJECTED", "CANCELLED"], default: "PENDING_REVIEW" },
  postedAt: Date,
  postedBy: { type: Schema.Types.ObjectId, ref: "User" },
  postingReason: String,
  balanceCredit: Number,
  cashRefund: Number,
  refundReference: String,
  restocked: Boolean,
  restoredCost: Number,
  source: String,
  categoryName: String,
  unitCost: Number,
  reviewedBy: { type: Schema.Types.ObjectId, ref: "User" },
  reviewedAt: Date,
  reviewReason: String,
  settlementPolicy: { type: String, default: "CREDIT_UNPAID_REFUND_PAID" },
  createdBy: { type: Schema.Types.ObjectId, required: true },
  requestHash: String,
}, { timestamps: true });
if (mongoose.models.MainCustomerReturn && !mongoose.models.MainCustomerReturn.schema.path("postedAt")) mongoose.deleteModel("MainCustomerReturn");
export default mongoose.models.MainCustomerReturn || mongoose.model("MainCustomerReturn", schema);
